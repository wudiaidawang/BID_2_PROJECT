# ── 生成扁平化的名称查找集合 ──
_PROTECTED_NAMES: List[str] = []
for entry in _LAW_ENTITIES:
    _PROTECTED_NAMES.extend(entry)
_PROTECTED_NAMES = sorted(set(_PROTECTED_NAMES), key=len, reverse=True)

# ── 法条号匹配模式 ──
_ARTICLE_PATTERNS = [
    re.compile(p) for p in [
        r'第[一二三四五六七八九十百零\d]+条',
        r'第[一二三四五六七八九十百零\d]+款',
        r'第[一二三四五六七八九十百零\d]+项',
        r'第[一二三四五六七八九十百零\d]+章',
        r'第[一二三四五六七八九十百零\d]+节',
        r'\d+条',
        r'\d+款',
    ]
]


def is_protected_entity(text: str) -> bool:
    """检查文本是否包含受保护的法规名称，Rewrite 层用于跳过改写"""
    for name in _PROTECTED_NAMES:
        if name in text:
            return True
    return False


def detect_regulation_entity(query: str) -> bool:
    """检测 query 是否明确指向法规法条（用于 Fusion 动态权重）

    识别：法条号（第X条/款/项/章/节）或法规全称/简称
    """
    # 法条号模式匹配
    for pat in _ARTICLE_PATTERNS:
        if pat.search(query):
            return True
    # 法规名称匹配（使用核心法规简称，避免误匹配）
    for name in _PROTECTED_NAMES:
        if len(name) >= 4 and name in query:
            return True
    return False


def get_protected_names() -> List[str]:
    """返回所有受保护名称（供外部使用）"""
    return _PROTECTED_NAMES[:]


def get_law_entities() -> List[Tuple[str, ...]]:
    """返回完整的法律实体注册表"""
    return _LAW_ENTITIES[:]


def count() -> int:
    """返回注册的法律实体数量"""
    return len(_LAW_ENTITIES)
